# ── D. Comparison Dashboard ────────────────────────────────────────────────────
def comparison_dashboard(stats_dict: dict,
                         add_threshold_line: True) -> tuple:
    """
    Bar chart comparing normalised feature importances across methods.

    Parameters
    ----------
    stats_dict : dict mapping method name -> DataFrame [Feature, Mean, Std, ...]
        Each DataFrame must have 'Feature' and 'Mean' columns (as returned by
        shap_analysis, permutation_importance_analysis, bootstrap_stability).
        The dictionary key is used as the legend label.
    add_threshold_line : bool, default True
        If True, draw a horizontal threshold line at
        ``μ + threshold_n_std × σ`` of the cross-method mean normalised
        importance, where μ = 1 / n_features (uniform baseline) and σ is the
        standard deviation across features of that mean. Set to None to omit.

    Returns
    -------
    fig : matplotlib Figure
    ax  : matplotlib Axes
    """
    def norm(s):
        s = s.abs()
        return s / s.sum() if s.sum() > 0 else s

    features = next(iter(stats_dict.values()))["Feature"].tolist()

    all_imp = pd.DataFrame({
        label: norm(df.set_index("Feature")["Mean"]).reindex(features)
        for label, df in stats_dict.items()
    })

    avg_importance = all_imp.mean(axis=1)
    rank_order = avg_importance.sort_values(ascending=False).index
    all_imp = all_imp.loc[rank_order]
    avg_importance = avg_importance.loc[rank_order]

    fig, ax = plt.subplots(figsize=(max(11, 0.6 * len(features)), 5))
    all_imp.plot.bar(ax=ax, width=0.72, edgecolor="white")
    ax.set_title("Feature Importance — Method Comparison", fontsize=12)
    ax.set_ylabel("Normalised importance")
    ax.set_xticklabels(all_imp.index, rotation=30, ha="right")

    if add_threshold_line is not None:
        n_features = len(features)
        sd = np.std(all_imp.values) / n_features
        mu = np.mean(all_imp.values) / n_features
        alpha = 0.05 # / len(features)  # Bonferroni correction for multiple comparisons
        z = stats.norm.ppf(1 - alpha / 2)        # 1.96 for alpha=0.05
        half_width = mu + z * sd # 95% upper bound of the null distribution of mean importance
    
        ax.axhline(half_width, color="black", lw=1.2, linestyle="--",
                   label="95% upper bound of null distribution")
        # label=f"threshold ({mu:.3f} + {z:.3f} × {sd:.3f} = {half_width:.3f})"
    ax.legend(loc="upper right")
    fig.tight_layout()
    return fig, ax



