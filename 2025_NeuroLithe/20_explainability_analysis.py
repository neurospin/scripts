def classification_report_cv(X: np.ndarray,
                             y: np.ndarray,
                             estimators: list,
                             cv) -> pd.DataFrame:
    """
    Evaluate a set of pre-fitted CV estimators out-of-fold and return a tidy
    metrics DataFrame.

    Each metric is reported with two strategies:

    - **Average-of-folds** (avg_folds ± std_folds): metric computed within each
      fold then averaged across folds — identical to what ``cross_val_score``
      reports.
    - **Pooled OOF** (pooled_oof): out-of-fold predictions concatenated across
      all folds, then scored once on the full vector — identical to what
      ``cross_val_predict`` followed by a metric call produces.

    Recall is broken down **per class label** (``Recall (class 0)``,
    ``Recall (class 1)``, …) so that sensitivity and specificity are reported
    separately instead of being collapsed into a single binary recall.

    Parameters
    ----------
    X          : ndarray (n_samples, n_features) — raw feature matrix
    y          : ndarray (n_samples,) — true class labels
    estimators : list of fitted pipelines, one per CV fold
    cv         : CV splitter used during fitting (must match the one used to
                 produce ``estimators``)

    Returns
    -------
    avg_folds : pd.DataFrame
        One row per metric, columns: ``metric``, ``avg_folds``, ``std_folds``,
        ``se_folds``, ``pooled_oof``, ``pval``, ``fold_values``.
        ``se_folds`` = std / √n_folds.
        ``pval``: one-sided p-value — binomial test (H0: score ≤ 0.5) for
        balanced accuracy and per-class recalls; Mann-Whitney U (H0: AUC ≤ 0.5)
        for ROC-AUC; NaN for Precision, F1, MCC.
    oof : pd.DataFrame
        Pooled OOF sklearn classification_report as a DataFrame (rows = class
        labels + averages, columns = precision / recall / f1-score / support).
    y_pred_cv  : ndarray (n_samples,) — pooled OOF hard predictions
    y_proba_cv : ndarray (n_samples,) — pooled OOF predicted probabilities
    """
    
    # Average-of-folds / "score-then-average": compute the metric within each fold,
    # then average across folds.

    print("\n━━━  Average-of-folds (AOF) Classification Report ━━━")

    y_pred_cv  = np.empty(len(y), dtype=int)
    y_proba_cv = np.empty(len(y))
    fold_ba, fold_auc, fold_prec, fold_f1, fold_mcc = [], [], [], [], []
    fold_rec_cls = []   # per-fold recall for each class: list of (n_classes,) arrays

    for (_, te), pipe in zip(cv.split(X, y), estimators):
        y_pred_cv[te]  = pipe.predict(X[te])
        y_proba_cv[te] = pipe.predict_proba(X[te])[:, 1]
        fold_ba.append(balanced_accuracy_score(y[te], y_pred_cv[te]))
        fold_auc.append(roc_auc_score(y[te], y_proba_cv[te]))
        fold_prec.append(precision_score(y[te], y_pred_cv[te], zero_division=0))
        fold_rec_cls.append(recall_score(y[te], y_pred_cv[te], average=None, zero_division=0))
        fold_f1.append(f1_score(y[te], y_pred_cv[te], zero_division=0))
        fold_mcc.append(matthews_corrcoef(y[te], y_pred_cv[te]))

    classes    = np.unique(y)
    n_folds    = len(fold_ba)
    N_test     = len(y)
    rec_pooled = recall_score(y, y_pred_cv, average=None, zero_division=0)  # (n_classes,)
    ba_pooled  = balanced_accuracy_score(y, y_pred_cv)
    auc_pooled = roc_auc_score(y, y_proba_cv)

    # p-values on pooled OOF
    pval_ba  = scipy_stats.binomtest(
        k=int(ba_pooled * N_test), n=N_test, p=0.5, alternative='greater').pvalue
    labels = np.unique(y)
    if len(labels) == 2:
        pval_auc = scipy_stats.mannwhitneyu(
            y_proba_cv[y == labels[0]], y_proba_cv[y == labels[1]], alternative='greater').pvalue
    else:
        pval_auc = np.nan  # Mann-Whitney U test is not defined for multiclass AUC
    rec_pvals = [
        scipy_stats.binomtest(
            k=int(rec_pooled[i] * np.sum(y == cls)),
            n=int(np.sum(y == cls)), p=0.5, alternative='greater').pvalue
        for i, cls in enumerate(classes)
    ]

    rows = [
        ("Balanced Accuracy", fold_ba,   ba_pooled,                                      pval_ba),
        ("ROC-AUC",           fold_auc,  auc_pooled,                                     pval_auc),
        ("Precision",         fold_prec, precision_score(y, y_pred_cv, zero_division=0), np.nan),
        *[(f"Recall (class {cls})", [r[i] for r in fold_rec_cls], rec_pooled[i], rec_pvals[i])
          for i, cls in enumerate(classes)],
        ("F1",                fold_f1,   f1_score(y, y_pred_cv, zero_division=0),        np.nan),
        ("MCC",               fold_mcc,  matthews_corrcoef(y, y_pred_cv),                np.nan),
    ]
    avg_folds = pd.DataFrame(
        [(name, np.mean(folds), np.std(folds), np.std(folds) / np.sqrt(n_folds), pooled, pval, folds)
         for name, folds, pooled, pval in rows],
        columns=["metric", "avg_folds", "std_folds", "se_folds", "pooled_oof", "pval", "fold_values"],
    )

    print("\n━━━  Model Performance  ━━━")
    print(f"  {'Metric':<24}  {'Avg-of-folds':>13}  {'±SE':>6}  {'Pooled OOF':>11}  {'p-value':>9}")
    print(f"  {'-'*24}  {'-'*13}  {'-'*6}  {'-'*11}  {'-'*9}")
    for _, row in avg_folds.iterrows():
        pval_str = f"{row.pval:>9.4f}" if not np.isnan(row.pval) else f"{'':>9}"
        print(f"  {row.metric:<24}  {row.avg_folds:>13.3f}  {row.se_folds:>6.3f}  {row.pooled_oof:>11.3f}  {pval_str}")

    print("\n━━━  Out-of-Fold (OOF) Classification Report ━━━")
    oof = pd.DataFrame(classification_report(y, y_pred_cv, output_dict=True)).T
    print(oof)

    return avg_folds, oof, y_pred_cv, y_proba_cv


